#!/usr/bin/env python3
"""Gate: the Web wrappers surface Godot enums as their value classes and keep Godot's `required`
returns non-null (task 128 C) -- the Kotlin/Wasm twin of `scripts/check_typed_enums.py`.

The Web wrappers (`web-runtime/.../api/generated/*.kt`, generated by `scripts/generate_web_wrappers.py`,
plus the hand-written facades beside them) do not call `getMethodBind`; every member that reaches
Godot names its opcode descriptor (`D.NODE_SET_PROCESS_MODE`). This gate ties each Kotlin function to
its Godot method through that descriptor and reads the COMMITTED sources:

  (a) typed slots -- each parameter whose Godot type is `enum::X` / `bitfield::X`, and the return of
      the function named after the method, uses the value class (`Node.ProcessMode`, `GodotError`),
      never a raw `Long`/`Int`; a property has its getter's type.
  (b) required returns -- an object return Godot marks `meta: "required"` is non-null and goes through
      `requireGodotReturn` (desktop/iOS semantics: a null throws naming the Godot method).
  (c) names -- every value emitted in a Web value class equals THE naming function
      (`godot_enum_model.enum_value_name`) under the frozen prefix lock, and every value class the
      Web tree emits is one the model knows under that owner (so Web and native names cannot drift).

    python3 scripts/check_web_typed_enums.py
    python3 scripts/check_web_typed_enums.py --root /tmp/scratch   # red runs on a scratch copy
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

TAG = "[web_typed_enums]"
DESCRIPTOR_RE = re.compile(r"\bD\.([A-Z][A-Z0-9_]+)\b")
PROPERTY_RE = re.compile(r"\b(?:val|var)\s+(\w+)\s*:\s*([\w.<>?, ]+?)\s*\n\s*get\(\)\s*=\s*(\w+)\(\)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root: Path = args.root.resolve()
    sys.path.insert(0, str(root / "scripts"))
    import godot_enum_model as model  # noqa: E402
    from check_typed_enums import blank_comments, parse_functions  # noqa: E402
    import generate_web_wrappers as web  # noqa: E402

    api = web.Api(root / "extension_api.json")
    lock = model.read_lock(root / "scripts/enum_prefix_lock.json")
    api_dir = root / "web-runtime/src/commonMain/kotlin/net/multigesture/kanama/api"
    files = sorted([*api_dir.glob("*.kt"), *(api_dir / "generated").glob("*.kt")])
    by_descriptor = {web.descriptor_name(call): call for call in web.INITIAL_BACKEND_CALLS}
    failures: list[str] = []

    def expected(godot_type: str) -> set[str] | None:
        spec = api.enum_for_godot_type(godot_type)
        if spec is None:
            return None
        names = {api.enum_type(spec), f"{model.API_PACKAGE}.{spec.kotlin_name}"}
        if spec.owner is not None:
            names.add(spec.name)  # inside the owner's own body
        return names

    slots = required = 0
    for path in files:
        text = blank_comments(path.read_text(encoding="utf-8"))
        rel = path.relative_to(root)
        fun_returns: dict[str, str] = {}
        for fun in parse_functions(text):
            used = {by_descriptor[d] for d in DESCRIPTOR_RE.findall(fun.body) if d in by_descriptor}
            if len(used) != 1:
                continue
            call = used.pop()
            method = api.method(call)
            policy = web.WRAPPER_POLICY.get(call.opcode, {})
            args_by_name = {web.param_name(a["name"]): a["type"] for a in method.get("arguments", ())}
            for pname, ptype in fun.params:
                want = expected(args_by_name.get(pname, ""))
                if want is None:
                    continue
                slots += 1
                if ptype.rstrip("?") not in want:
                    failures.append(
                        f"{rel}:{fun.line}: {fun.name}({pname}: {ptype}) -- Godot {call.class_name}.{call.method_name} "
                        f"types `{pname}` {args_by_name[pname]}; expected {' / '.join(sorted(want))}"
                    )
            rv = method.get("return_value") or {}
            primary = fun.name in (web.member_name(call, policy), web.camel(call.method_name))
            if not primary or fun.ret is None or "ret" in policy:
                continue
            fun_returns[fun.name] = fun.ret
            want = expected(rv.get("type", ""))
            if want is not None:
                slots += 1
                if fun.ret.rstrip("?") not in want:
                    failures.append(
                        f"{rel}:{fun.line}: {fun.name}(): {fun.ret} -- Godot {call.class_name}.{call.method_name} "
                        f"returns {rv['type']}; expected {' / '.join(sorted(want))}"
                    )
            elif rv.get("meta") == "required":
                required += 1
                if fun.ret.endswith("?"):
                    failures.append(
                        f"{rel}:{fun.line}: {fun.name}(): {fun.ret} -- Godot marks {call.class_name}.{call.method_name} "
                        "`meta: \"required\"`: the return must be non-null (decision 9)"
                    )
                elif "requireGodotReturn" not in fun.body:
                    failures.append(
                        f"{rel}:{fun.line}: {fun.name}() -- required return of {call.class_name}.{call.method_name} "
                        "does not go through requireGodotReturn (a null must throw, never pass silently)"
                    )
        for m in PROPERTY_RE.finditer(text):
            prop, ptype, getter = m.group(1), m.group(2).strip(), m.group(3)
            if getter in fun_returns and fun_returns[getter] != ptype:
                line = text.count("\n", 0, m.start()) + 1
                failures.append(f"{rel}:{line}: property {prop}: {ptype} -- its getter {getter}() returns {fun_returns[getter]}")

    # (c) value names under the lock, value classes known to the model under that owner.
    by_owner = {(s.kotlin_owner, s.simple_name): s for s in api.enums.values()}
    decl_re = re.compile(r"(?m)^(?:(?:open|abstract|internal|private|data)\s+)*(?:class|object)\s+(\w+)")
    value_class_re = re.compile(r"\bvalue\s+class\s+(\w+)")
    value_re = re.compile(r"^\s*val\s+([A-Z][A-Z0-9_]*)\s*:\s*(\w+)\s*get\(\)\s*=\s*(\w+)\((-?\d+)L\)\s*$")
    values = classes = 0
    for path in files:
        text = blank_comments(path.read_text(encoding="utf-8"))
        rel = path.relative_to(root)
        decls = [(m.start(), m.group(1)) for m in decl_re.finditer(text)]
        current = None
        offset = 0
        for lineno, line in enumerate(text.splitlines(), 1):
            start, offset = offset, offset + len(line) + 1
            vc = value_class_re.search(line)
            if vc:
                owner = None
                if line.startswith(" "):
                    for decl_start, name in decls:
                        if decl_start <= start:
                            owner = name
                current = by_owner.get((owner, vc.group(1)))
                classes += 1
                if current is None:
                    failures.append(f"{rel}:{lineno}: value class {owner + '.' if owner else ''}{vc.group(1)} is no Godot enum of the model")
                continue
            vm = value_re.match(line)
            if current is None or not vm or vm.group(2) != current.simple_name:
                continue
            values += 1
            prefix = lock.get(current.key, "")
            allowed = {model.enum_value_name(prefix, v.name): v.value for v in current.values}
            if vm.group(1) not in allowed:
                failures.append(
                    f"{rel}:{lineno}: {current.kotlin_name}.{vm.group(1)} is not a value name the naming function gives "
                    f"under the locked prefix {prefix!r}"
                )
            elif allowed[vm.group(1)] != int(vm.group(4)) and not any(
                model.enum_value_name(prefix, v.name) == vm.group(1) and v.value == int(vm.group(4)) for v in current.values
            ):
                failures.append(f"{rel}:{lineno}: {current.kotlin_name}.{vm.group(1)} = {vm.group(4)}, Godot says {allowed[vm.group(1)]}")

    if failures:
        print(f"{TAG} FAIL {len(failures)} problem(s):", file=sys.stderr)
        for failure in failures[:80]:
            print(f"    {failure}", file=sys.stderr)
        return 1
    print(
        f"{TAG} PASS {slots} Web enum/bitfield slots typed, {required} required returns non-null via "
        f"requireGodotReturn, {classes} value classes / {values} value names match the model and lock "
        f"({len(files)} Web api files)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
