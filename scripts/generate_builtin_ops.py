WEB_INPUT_TYPES = {"float", "int", "bool", "Vector2", "Vector3", "Color", "Vector2i", "Vector3i", "Quaternion", "Plane"}
DRAW_RE = re.compile(r"\b(?:nv|ri|rnz|rs|rl|rb)\(\)")


def summary_key(key: str) -> str:
    return key.replace(" ", "_")


def web_capable(key: str, web_members: dict[str, set]) -> bool:
    cls, types, fn, ptype = ENTRY_META[key]
    if cls not in web_members or not set(types) <= WEB_INPUT_TYPES:
        return False
    found = web_members[cls]
    if ptype is None:
        return any(name == fn for name, _ in found)
    return (fn, ptype) in found


def web_members_now(web_source: str) -> dict[str, set]:
    return {cls: hand_members_all(class_body(web_source, cls)) for cls, vt in VALUE_TYPES.items() if vt.web}


def hand_members_all(body: str) -> set[tuple[str, str | None]]:
    """Every `fun` of [body], generated regions included."""
    return {(m.group("name"), m.group("ptype")) for m in FUN_RE.finditer(body) if not m.group("receiver")}


def load_expected() -> dict[str, str]:
    if not EXPECTED_PATH.exists():
        return {}
    return json.loads(EXPECTED_PATH.read_text(encoding="utf-8"))["pure"]


