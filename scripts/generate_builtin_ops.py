def indent(src: str, prefix: str) -> str:
    return "\n".join(prefix + line if line else line for line in src.splitlines())


def render_region(name: str, sources: list[str], begin: str, end: str, pad: str) -> str:
    lines = [pad + begin.format(name=name, gen=MARKER_GEN)]
    for src in sources:
        lines.append(indent(src, pad))
        lines.append("")
    lines.append(pad + end.format(name=name))
    return "\n".join(lines)


def comparison_key(text: str) -> str:
    text = re.sub(r"/\*\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r",(\s*[)\]])", r"\1", text)
    text = text.replace(";", "")
    return re.sub(r"\s+", "", text)


def splice(source: str, name: str, region: str, begin: str, end: str, anchor) -> str:
    """Replace the [name] region in [source], or insert it at [anchor](source) when absent."""
    b = begin.format(name=name, gen=MARKER_GEN)
    e = end.format(name=name)
    if b in source:
        start = source.rfind("\n", 0, source.index(b)) + 1
        stop = source.index(e) + len(e)
        old = source[start:stop]
        if comparison_key(old) == comparison_key(region):
            return source
        return source[:start] + region + source[stop:]
    pos = anchor(source)
    return source[:pos] + region + "\n\n" + source[pos:]


def class_companion_anchor(name: str, web: bool):
    def anchor(source: str) -> int:
        start = re.search(rf"^(?:data |value |@JvmInline\s+value )?class {name}\b", source, re.M).start()
        body = class_body(source, name)
        body_start = source.index(body, start)
        match = re.search(r"^  (?:internal )?companion object", body, re.M)
        if match:
            return body_start + match.start()
        # No companion: before the closing brace.
        close = body_start + len(body) - 1
        return source.rfind("\n", 0, close) + 1

    return anchor


def companion_open_anchor(name: str):
    def anchor(source: str) -> int:
        start = re.search(rf"^(?:data |value |@JvmInline\s+value )?class {name}\b", source, re.M).start()
        body = class_body(source, name)
        body_start = source.index(body, start)
        match = re.search(r"^  companion object \{\n", body, re.M)
        if not match:
            raise SystemExit(f"[generate_builtin_ops] {name} has statics but no public `companion object {{`")
        return body_start + match.end()

    return anchor


def render_marshalling(api: dict, members: list[Member]) -> str:
    variant_ids = {}
    for enum in api["global_enums"]:
        if enum["name"] == "Variant.Type":
            for value in enum["values"]:
                variant_ids[value["name"].removeprefix("TYPE_").replace("_", "")] = value["value"]
    out = [
        f"// GENERATED by {GENERATOR} from extension_api.json — do not edit.",
        "package net.multigesture.kanama.types",
        "",
        "import kotlin.jvm.JvmField",
        "import net.multigesture.kanama.binding.runtime.BuiltinFrame",
        "import net.multigesture.kanama.binding.runtime.BuiltinMethod",
        "",
        "// The value types' facade glue (task 134 B): each type's Godot memory layout written into a",
        "// BuiltinFrame slot and read back from the return slot, and one BuiltinMethod constant per",
        "// engine-backed method (resolved on its first call). Nothing here allocates per call.",
        "",
        "/** The calling thread's builtin-call frame (see `BuiltinFrame.expect.kt`). */",
        "@Suppress(\"NOTHING_TO_INLINE\")",
        "internal inline fun builtinFrame(): BuiltinFrame = net.multigesture.kanama.binding.runtime.builtinFrame()",
        "",
    ]
    getter = {"real": "retReal", "int": "retInt32", "color": "retFloat32"}
    putter = {"real": "putReal", "int": "putInt32", "color": "putFloat32"}
    for name, vt in VALUE_TYPES.items():
        out.append(f"internal fun BuiltinFrame.put(slot: Int, v: {name}) {{")
        for i, expr in enumerate(vt.pack):
            out.append(f"  {putter[vt.kind]}(slot, {i}, {expr})")
        out.append("}")
        out.append("")
        unpack = re.sub(r"c\[(\d+)\]", lambda mm: f"{getter[vt.kind]}({mm.group(1)})", vt.unpack)
        out.append(f"internal fun BuiltinFrame.ret{name}(): {name} = {unpack}")
        out.append("")
    by_class: dict[str, list[Member]] = {}
    for member in members:
        if member.impl == "facade":
            by_class.setdefault(member.cls, []).append(member)
    for cls, facade in by_class.items():
        vid = variant_ids[cls.upper()]
        out.append(f"/** {cls}'s engine-backed builtin methods. */")
        out.append(f"internal object {cls}Methods {{")
        for member in facade:
            m = member.godot
            kn = kotlin_name(cls, m["name"])
            out.append(f"  @JvmField val {kn} = BuiltinMethod({vid}, \"{m['name']}\", {m['hash']}L)")
            out.append("")
        if out[-1] == "":
            out.pop()
        out.append("}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


SCALAR_LEFT_TYPES = {"Vector2", "Vector2i", "Vector3", "Vector3i", "Vector4", "Vector4i", "Quaternion", "Color"}


def render_scalar_ops(api: dict, web: bool) -> str:
    out = [
        f"// GENERATED by {GENERATOR} from extension_api.json — do not edit.",
        "package net.multigesture.kanama.types",
        "",
        "// The operators whose left operand is not a value type (task 134 B): GDScript's `2.0 * v` and",
        "// `points * transform`. Godot evaluates `scalar * v` as `v * scalar`, so these delegate.",
        "",
    ]
    for left, kinds in (("int", ("Int", "Long")), ("float", ("Double",))):
        cls_api = builtin_class(api, left)
        for op in cls_api["operators"]:
            right = op.get("right_type", "")
            if op["name"] != "*" or right not in SCALAR_LEFT_TYPES:
                continue
            if web and not (VALUE_TYPES[right].web):
                continue
            for k in kinds:
                out.append(f"operator fun {k}.times(other: {right}): {kotlin_type(op['return_type'])} = other * this")
                out.append("")
    if not web:
        out.append("operator fun List<Vector2>.times(transform: Transform2D): List<Vector2> =")
        out.append("  map { transform2DXformInv(transform, it) }")
        out.append("")
        out.append("operator fun List<Vector3>.times(transform: Transform3D): List<Vector3> =")
        out.append("  map { transform3DXformInv(transform, it) }")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


