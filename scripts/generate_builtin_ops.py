            "\t\tfor c in [value.normal, value.d]: mix(name, c)",
            "\telif value is Basis:",
            "\t\tfor c in [value.x, value.y, value.z]: mix(name, c)",
            "\telif value is Transform2D:",
            "\t\tfor c in [value.x, value.y, value.origin]: mix(name, c)",
            "\telif value is Transform3D:",
            "\t\tfor c in [value.basis, value.origin]: mix(name, c)",
            "\telif value is Projection:",
            "\t\tfor c in [value.x, value.y, value.z, value.w]: mix(name, c)",
            "\telif value is PackedVector2Array or value is PackedVector3Array:",
            "\t\tfor c in value: mix(name, c)",
            "\telse:",
            "\t\tpush_error(\"no parity mix for %s\" % type_string(typeof(value)))",
