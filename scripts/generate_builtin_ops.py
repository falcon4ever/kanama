def class_file(cls: str) -> Path:
    return TYPES_DIR / f"{cls}.kt"


def regenerate(api: dict) -> dict[Path, str]:
    """Every output path -> its regenerated content."""
    outputs: dict[Path, str] = {}
    sources = {cls: class_file(cls).read_text(encoding="utf-8") for cls in OWNED_CLASSES}
    hand_bodies = {cls: class_body(src, cls) for cls, src in sources.items()}
    HAND_BODIES.clear()
    HAND_BODIES.update({cls: strip_regions(body) for cls, body in hand_bodies.items()})
    members = build_members(api, hand_bodies)
    for cls in OWNED_CLASSES:
        source = sources[cls]
        instance = [m.code for m in members if m.cls == cls and m.code and not m.static]
        statics = [m.code for m in members if m.cls == cls and m.code and m.static]
        if instance:
            region = render_region(cls, instance, BEGIN, END, "  ")
            source = splice(source, cls, region, BEGIN, END, class_companion_anchor(cls, False))
        if statics:
            region = render_region(cls, statics, SBEGIN, SEND, "    ")
            source = splice(source, cls, region, SBEGIN, SEND, companion_open_anchor(cls))
        outputs[class_file(cls)] = source
    outputs[MARSHALLING] = render_marshalling(api, members)
    outputs[SCALAR_OPS] = render_scalar_ops(api, web=False)
    # Web: the pure, component-wise members of the classes it has.
    web_source = WEB_TYPES.read_text(encoding="utf-8")
    for cls, vt in VALUE_TYPES.items():
        if not vt.web:
            continue
        web_body = class_body(web_source, cls)
        web_hand = hand_members(web_body)
        codes = []
        for m in members:
            if m.cls != cls or not m.web:
                continue
            fn_match = re.search(r"fun\s+(\w+)\s*\(\s*(?:\w+\s*:\s*([\w<>]+))?", m.web)
            if fn_match and has_member(web_hand, fn_match.group(1), fn_match.group(2)):
                continue
            if fn_match and not fn_match.group(2) and has_member(web_hand, fn_match.group(1)):
                continue
            codes.append(m.web)
        if codes:
            region = render_region(cls, codes, BEGIN, END, "  ")
            web_source = splice(web_source, cls, region, BEGIN, END, class_companion_anchor(cls, True))
    outputs[WEB_TYPES] = web_source
    outputs[WEB_SCALAR_OPS] = render_scalar_ops(api, web=True)
    pure, facade = parity_entries(members)
    outputs[PARITY_KT] = render_parity_kt(pure, facade)
    outputs[PARITY_GD] = render_parity_gd(pure, facade)
    outputs[WEB_TEST] = render_web_test(pure, web_source)
    return outputs


def members_for_gate(api: dict) -> list[Member]:
    sources = {cls: class_file(cls).read_text(encoding="utf-8") for cls in OWNED_CLASSES}
    hand_bodies = {cls: class_body(src, cls) for cls, src in sources.items()}
    return build_members(api, hand_bodies)


def same(path: Path, content: str) -> bool:
    if not path.exists():
        return False
    current = path.read_text(encoding="utf-8")
    if path.suffix == ".kt":
        return comparison_key(current) == comparison_key(content)
    return current == content


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--record-parity",
        metavar="LOG",
        type=Path,
        help="record the GDScript hashes of the Web-capable parity entries from a runtime smoke log",
    )
    mode.add_argument(
        "--verify-recorded",
        metavar="LOG",
        type=Path,
        help="fail when the recorded hashes differ from the log's GDScript line (runtime smoke)",
    )
    args = parser.parse_args()
    api = load_api()
    outputs = regenerate(api)
    if args.record_parity or args.verify_recorded:
        log = (args.record_parity or args.verify_recorded).read_text(encoding="utf-8", errors="replace")
        live = parse_gdscript_pure(log)
        sources = {cls: class_file(cls).read_text(encoding="utf-8") for cls in OWNED_CLASSES}
        members = build_members(api, {cls: class_body(src, cls) for cls, src in sources.items()})
        pure, _ = parity_entries(members)
        keys = web_parity_keys(pure, outputs[WEB_TYPES])
        if args.record_parity:
            missing = [k for k in keys if k not in live]
            if missing:
                raise SystemExit(f"[generate_builtin_ops] the log lacks {len(missing)} entries: {missing[:5]}")
            EXPECTED_PATH.parent.mkdir(parents=True, exist_ok=True)
            payload = {
                "comment": "Godot 4.7.2 GDScript hashes of the builtin parity row (float32 build), for the "
                "entries the Web value types run (WebBuiltinParityTest). Written by "
                "`scripts/generate_builtin_ops.py --record-parity <runtime smoke log>`.",
                "pure": {k: live[k] for k in keys},
            }
            EXPECTED_PATH.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
            print(f"[generate_builtin_ops] recorded {len(keys)} Web parity hashes; rerun --write for the Web test")
            return 0
        recorded = load_expected()
        problems = [f"{k}: recorded {v}, GDScript {live.get(k)}" for k, v in recorded.items() if live.get(k) != v]
        problems += [f"{k}: not recorded (run --record-parity)" for k in keys if k not in recorded]
        if problems:
            print(f"[generate_builtin_ops] FAIL: the recorded Web parity hashes are stale ({len(problems)}):", file=sys.stderr)
            for line in problems[:20]:
                print(f"    {line}", file=sys.stderr)
            return 1
        print(f"[generate_builtin_ops] PASS: {len(recorded)} recorded Web parity hashes match GDScript")
        return 0
    stale = [path for path, content in outputs.items() if not same(path, content)]
    if args.check:
        if stale:
            print(f"[generate_builtin_ops] FAIL: {len(stale)} file(s) differ from a fresh generation:", file=sys.stderr)
            for path in stale:
                print(f"    {path.relative_to(ROOT)}", file=sys.stderr)
            print("    fix: python3 scripts/generate_builtin_ops.py --write && ./gradlew ktfmtFormat", file=sys.stderr)
            return 1
        print(f"[generate_builtin_ops] PASS: {len(outputs)} outputs current")
        return 0
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
    print(f"[generate_builtin_ops] wrote {len(stale)} of {len(outputs)} outputs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
