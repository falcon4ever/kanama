FUN_RE = re.compile(
    r"\bfun\s+(?:<[^>]*>\s*)?(?:(?P<receiver>[A-Za-z0-9_.<>]+)\.)?(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*\("
    r"\s*(?:(?:vararg\s+)?[A-Za-z_][A-Za-z0-9_]*\s*:\s*(?P<ptype>[A-Za-z0-9_.<>?]+))?"
)


def strip_regions(source: str) -> str:
    return re.sub(
        r"// ===== BEGIN GENERATED BUILTIN (?:MEMBERS|STATICS): .*?// ===== END GENERATED BUILTIN (?:MEMBERS|STATICS): \w+ =====",
        "",
        source,
        flags=re.S,
    )


def class_body(source: str, name: str) -> str:
    """The text of class [name]'s body in a file that may hold several classes (the Web one)."""
    match = re.search(rf"^(?:data |value |@JvmInline\s+value )?class {name}\b", source, re.M)
    if not match:
        return ""
    brace = source.find("{", match.end())
    # A primary constructor's parentheses may hold default values with braces; skip them first.
    paren = source.find("(", match.end())
    if 0 <= paren < brace:
        depth = 0
        for i in range(paren, len(source)):
            if source[i] == "(":
                depth += 1
            elif source[i] == ")":
                depth -= 1
                if depth == 0:
                    brace = source.find("{", i)
                    break
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[brace : i + 1]
    return source[brace:]


def hand_members(body: str) -> set[tuple[str, str | None]]:
    """(name, first parameter type) of each `fun` in [body] outside the generated regions."""
    found: set[tuple[str, str | None]] = set()
    for match in FUN_RE.finditer(strip_regions(body)):
        if match.group("receiver"):
            continue
        found.add((match.group("name"), match.group("ptype")))
    return found


def has_member(members: set[tuple[str, str | None]], name: str, ptype: str | None = "*") -> bool:
    if ptype == "*":
        return any(n == name for n, _ in members)
    return (name, ptype) in members


