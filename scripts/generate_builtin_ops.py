def parse_gdscript_pure(log: str) -> dict[str, str]:
    match = re.search(r"BuiltinParity gdscript pure=n=\d+ (.*)", log)
    if not match:
        raise SystemExit("[generate_builtin_ops] the log has no `BuiltinParity gdscript pure=` line")
    return dict(item.rsplit("=", 1) for item in match.group(1).split())


ENGINE_CALL_RE = re.compile(r"\bbuiltinFrame\s*\(")
HAND_BODIES: dict[str, str] = {}


def member_calls_engine(member: Member) -> bool:
    """A hand-written method whose body reaches the engine (facade) rather than Kotlin math."""
    body = HAND_BODIES.get(member.cls, "")
    kn = kotlin_name(member.cls, member.godot["name"])
    match = re.search(rf"\bfun\s+{re.escape(kn)}\s*\(", body)
    if not match:
        return False
    nxt = re.search(r"\n  (?:(?:override |operator |internal |private )*fun |val |companion |// =====)", body[match.end():])
    snippet = body[match.start() : match.end() + (nxt.start() if nxt else len(body))]
    if ENGINE_CALL_RE.search(snippet):
        return True
    # One level of private helper (e.g. `fromGodotRealArray(BuiltinCalls...)` lives in the body).
    return False


