def web_method_ok(cls: str, name: str) -> bool:
    return name in WEB_METHOD_OK.get(cls, set())


def web_op_ok(cls: str, op: dict) -> bool:
    right = op.get("right_type", "")
    return right in ("", "int", "float", cls) and not (cls == "Plane" and right)


