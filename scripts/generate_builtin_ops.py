#!/usr/bin/env python3
"""Generate the value types' builtin operators and methods from extension_api.json (task 134 B).

Godot declares, per builtin class, an operator list (`builtin_classes[*].operators`) and a method
list (`builtin_classes[*].methods`). This generator gives every value type (Vector2 ... Color,
plus RID) a Kotlin member for each of them, in one region per class it owns:

  // ===== BEGIN GENERATED BUILTIN MEMBERS: Vector2 (generate_builtin_ops.py) =====
  // ===== BEGIN GENERATED BUILTIN STATICS: Vector2 (generate_builtin_ops.py) =====  (in the companion)

Two implementations, chosen per member:

* **pure Kotlin** -- every operator, and the methods in PURE_METHODS: Godot's own formula, ported
  with Godot's operand order and evaluated at the stored `real_t` width (component-wise ones are
  emitted from templates here; the composite ones call the hand-ported formulas in
  `types/BuiltinFormulas.kt` and `types/shared/RealMath.kt`/`BuiltinMath.kt`), so the result is the
  engine's to the bit;
* **the BuiltinCalls facade** -- every other method: the engine runs it (exact Godot semantics,
  edge cases and MATH_CHECKS errors included).

Members that are already hand-written in the class (outside the regions) are left alone and only
counted. The runtime smoke proves both kinds against GDScript: this generator also writes the
probe pair `example_project/BuiltinParitySmoke.kt` + `builtin_parity_ref.gd`, which print a
per-member FNV hash over fixed-seed random inputs -- every pure member (generated or hand-written)
over PARITY_INPUTS inputs, every facade-backed member over FACADE_INPUTS -- and
`scripts/runtime_smoke.sh` requires the Kotlin and the GDScript line to be identical.

Outputs (all regenerated by --write, compared by --check):
  * the GENERATED BUILTIN regions of `src/commonMain/.../types/<Type>.kt`;
  * `src/commonMain/.../types/BuiltinMarshalling.kt` (layouts, method binds, facade shims);
  * `src/commonMain/.../types/BuiltinScalarOperators.kt` (`2.0 * v`, `points * transform`);
  * the Web value types' GENERATED BUILTIN regions (`web-runtime/.../types/WebValueTypes.kt`) and
    `WebScalarOperators.kt`: the pure members of the classes the Web backend has (it has no
    builtin-call path yet, so facade members wait for parcel D);
  * the parity probe pair above.

The comparison ignores whitespace, trailing commas and KDoc (ktfmt formats the regions and
`sync_kdoc_from_godot_docs.py` documents them), so run `./gradlew ktfmtFormat` and the KDoc sync
after --write. `scripts/check_builtin_coverage.py` is the gate that every API operator and method
has a member or a recorded reason.

Usage:
    python3 scripts/generate_builtin_ops.py --write
    python3 scripts/generate_builtin_ops.py --check
"""

