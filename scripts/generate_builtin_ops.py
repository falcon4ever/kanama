def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def kotlin_name(cls: str, method: str) -> str:
    return NAME_OVERRIDES.get((cls, method), camel(method))


def kotlin_type(godot: str) -> str | None:
    if godot in KOTLIN_SCALAR:
        return KOTLIN_SCALAR[godot]
    if godot in VALUE_TYPES or godot == "RID":
        return godot
    if godot in LIST_TYPES:
        return f"List<{LIST_TYPES[godot]}>"
    return None


def kotlin_default(godot_type: str, value: str) -> str:
    if godot_type == "float":
        return value if any(ch in value for ch in ".e") else f"{value}.0"
    if godot_type == "int":
        return f"{value}L"
    if godot_type == "bool":
        return value
    match = re.fullmatch(r"(\w+)\((.*)\)", value)
    if match and match.group(1) in VALUE_TYPES:
        args = [a.strip() for a in match.group(2).split(",")]
        if VALUE_TYPES[match.group(1)].kind == "int":
            return f"{match.group(1)}({', '.join(args)})"
        return f"{match.group(1)}({', '.join(a if '.' in a else a + '.0' for a in args)})"
    raise SystemExit(f"[generate_builtin_ops] no Kotlin form for default {godot_type} = {value}")


