def load_api() -> dict:
    return json.loads(API_PATH.read_text(encoding="utf-8"))


def builtin_class(api: dict, name: str) -> dict:
    for cls in api["builtin_classes"]:
        if cls["name"] == name:
            return cls
    raise SystemExit(f"[generate_builtin_ops] {name} is not a builtin class")


def op_key(cls: str, op: dict) -> str:
    right = op.get("right_type", "")
    return f"{op['name']} {cls}" if not right else f"{cls} {op['name']} {right}"


def build_members(api: dict, hand_bodies: dict[str, str]) -> list[Member]:
    members: list[Member] = []
    for cls in OWNED_CLASSES:
        cls_api = builtin_class(api, cls)
        hand = hand_members(hand_bodies.get(cls, ""))
        vt = VALUE_TYPES.get(cls)
        seen_sources: set[tuple[str, str]] = set()
        for op in interesting_ops(cls_api):
            key = op_key(cls, op)
            if op["name"] in ("%",) and op.get("right_type") in ("Variant",):
                continue
            produced = op_members(cls, op, hand)
            for fn, ptype, src in produced:
                if (fn, ptype) in seen_sources:
                    continue
                seen_sources.add((fn, ptype))
                if has_member(hand, fn, ptype if ptype else None) or (not ptype and has_member(hand, fn)):
                    members.append(Member(cls, key, "op", "hand-pure", godot=op))
                    continue
                web = src if (vt and vt.web and web_op_ok(cls, op)) else ""
                members.append(Member(cls, key, "op", "pure", src, godot=op, web=web))
        for m in cls_api.get("methods", []):
            key = f"{cls}.{m['name']}"
            kn = kotlin_name(cls, m["name"])
            static = m.get("is_static", False)
            if has_member(hand, kn) or (cls, m["name"]) in PROPERTY_MEMBERS:
                members.append(Member(cls, key, "method", "hand", static=static, godot=m))
                continue
            if (cls, m["name"]) in DEFERRED_METHODS:
                members.append(Member(cls, key, "method", "deferred", static=static, godot=m, reason=DEFERRED_METHODS[(cls, m["name"])]))
                continue
            if m["name"] in PURE_METHODS.get(cls, set()):
                src = pure_method(cls, m)
                web = src if (vt and vt.web and web_method_ok(cls, m["name"])) else ""
                members.append(Member(cls, key, "method", "pure", src, static=static, godot=m, web=web))
                continue
            reason = facade_supported(m)
            if reason or vt is None:
                members.append(Member(cls, key, "method", "deferred", static=static, godot=m, reason=reason or "no facade layout"))
                continue
            members.append(Member(cls, key, "method", "facade", facade_method(cls, m), static=static, godot=m))
    return members


