@dataclass
class Member:
    cls: str
    key: str  # coverage/parity key: "Vector2.abs", "Vector2 * Transform2D", "unary- Vector2"
    kind: str  # "op", "method"
    impl: str  # "pure", "facade", "hand-pure", "hand-facade", "deferred"
    code: str = ""  # Kotlin member source ("" for hand-written / deferred)
    static: bool = False
    godot: dict = field(default_factory=dict)
    reason: str = ""
    web: str = ""  # the Web copy of [code] ("" when the Web class does not get it)


OP_KOTLIN = {"+": "plus", "-": "minus", "*": "times", "/": "div", "%": "rem", "unary-": "unaryMinus", "unary+": "unaryPlus"}
COMPARE_OPS = {"<", "<=", ">", ">="}


def raw_ctor(vt: ValueType, values: list[str]) -> str:
    if vt.kind == "int":
        return f"{vt.name}({', '.join(values)})"
    return f"raw({', '.join(values)})"


def componentwise(vt: ValueType, fmt: str) -> str:
    """`fmt` over every component: `{c}` is this component, `{o}` the other's."""
    return raw_ctor(vt, [fmt.format(c=c, o=f"other.{c}") for c in vt.comps])


def scalar_param(right: str) -> list[tuple[str, str]]:
    """Kotlin parameter types for a Godot scalar right operand, and how each converts."""
    if right == "int":
        return [("Int", "Int"), ("Long", "Long")]
    return [("Double", "Double")]


def op_members(cls: str, op: dict, hand: set) -> list[tuple[str, str, str]]:
    """(kotlin member name, first param type, source) for one API operator of [cls]."""
    name = op["name"]
    right = op.get("right_type", "")
    ret = op["return_type"]
    vt = VALUE_TYPES.get(cls)
    out: list[tuple[str, str, str]] = []

    if name in ("unary-", "unary+"):
        fn = OP_KOTLIN[name]
        if name == "unary+":
            body = "this"
        elif cls == "Color":
            body = componentwise(vt, "1.0f - {c}")
        elif cls == "Plane":
            body = "raw(-normal, -rawD)"
        else:
            body = componentwise(vt, "-{c}")
        return [(fn, "", f"operator fun {fn}(): {cls} = {body}")]

    if name in COMPARE_OPS:
        if cls == "RID":
            return [("compareTo", cls, f"operator fun compareTo(other: {cls}): Int = value.toULong().compareTo(other.value.toULong())")]
        steps = [f"godotCompareStep({c}, other.{c})" for c in vt.comps]
        lines = [f"operator fun compareTo(other: {cls}): Int {{"]
        for i, step in enumerate(steps[:-1]):
            lines.append(f"  val c{i} = {step}")
            lines.append(f"  if (c{i} != 0) return c{i}")
        lines.append(f"  return {steps[-1]}")
        lines.append("}")
        return [("compareTo", cls, "\n".join(lines))]

    fn = OP_KOTLIN[name]
    if right in ("int", "float"):
        out = []
        for ptype, _ in scalar_param(right):
            if ptype in ("Int", "Long") and vt and vt.kind != "int":
                src = f"operator fun {fn}(scalar: {ptype}): {ret} = {fn}(scalar.toDouble())"
            elif vt and vt.kind == "int" and ret == cls:
                if ptype == "Long":
                    src = f"operator fun {fn}(scalar: Long): {ret} = {fn}(scalar.toInt())"
                else:
                    sym = {"times": "*", "div": "/", "rem": "%"}[fn]
                    src = f"operator fun {fn}(scalar: Int): {ret} = " + raw_ctor(vt, [f"{c} {sym} scalar" for c in vt.comps])
            elif vt and vt.kind == "int":  # Vector2i * float -> Vector2
                sym = {"times": "*", "div": "/"}[fn]
                comps = ", ".join(f"narrowReal({c}.toDouble()) {sym} s" for c in vt.comps)
                src = f"operator fun {fn}(scalar: Double): {ret} {{\n  val s = narrowReal(scalar)\n  return {ret}.raw({comps})\n}}"
            elif cls == "Color":
                sym = {"times": "*", "div": "/"}[fn]
                src = f"operator fun {fn}(scalar: Double): Color {{\n  val s = scalar.toFloat()\n  return {componentwise(vt, '{c} ' + sym + ' s')}\n}}"
            elif cls in ("Vector2", "Vector3", "Vector4", "Quaternion"):
                sym = {"times": "*", "div": "/"}[fn]
                if cls == "Quaternion" and fn == "div":
                    # `Quaternion::operator/(real_t s)` is `*this * (1 / s)`.
                    src = "operator fun div(scalar: Double): Quaternion {\n  val s = narrowReal(1.0) / narrowReal(scalar)\n  return " + componentwise(vt, "{c} * s") + "\n}"
                else:
                    src = f"operator fun {fn}(scalar: Double): {cls} {{\n  val s = narrowReal(scalar)\n  return {componentwise(vt, '{c} ' + sym + ' s')}\n}}"
            elif cls == "Basis":
                sym = {"times": "*", "div": "/"}[fn]
                src = f"operator fun {fn}(scalar: Double): Basis {{\n  val s = narrowReal(scalar)\n  return basisMap(this) {{ it {sym} s }}\n}}"
            elif cls == "Transform2D":
                sym = {"times": "*", "div": "/"}[fn]
                src = f"operator fun {fn}(scalar: Double): Transform2D = Transform2D(x {sym} scalar, y {sym} scalar, origin {sym} scalar)"
            elif cls == "Transform3D":
                sym = {"times": "*", "div": "/"}[fn]
                src = f"operator fun {fn}(scalar: Double): Transform3D {{\n  val s = narrowReal(scalar)\n  return Transform3D(basisMap(basis) {{ it {sym} s }}, origin {sym} scalar)\n}}"
            else:
                raise SystemExit(f"[generate_builtin_ops] no template for {cls} {name} {right}")
            out.append((fn, ptype, src))
        return out

    if right == cls and vt and vt.comps and name in ("+", "-", "*", "/", "%"):
        sym = name
        return [(fn, cls, f"operator fun {fn}(other: {cls}): {cls} = " + componentwise(vt, "{c} " + sym + " {o}"))]

    composite = {
        ("Vector2", "Transform2D"): "transform2DXformInv(other, this)",
        ("Rect2", "Transform2D"): "transform2DXformInvRect(other, this)",
        ("Transform2D", "Transform2D"): "transform2DMultiply(this, other)",
        ("Transform2D", "Vector2"): "transform2DXform(this, other)",
        ("Transform2D", "Rect2"): "transform2DXformRect(this, other)",
        ("Transform2D", "PackedVector2Array"): "other.map { transform2DXform(this, it) }",
        ("Vector3", "Quaternion"): "quaternionXformInv(other, this)",
        ("Vector3", "Basis"): "basisXformInv(other, this)",
        ("Vector3", "Transform3D"): "transform3DXformInv(other, this)",
        ("Vector4", "Projection"): "projectionXformInv(other, this)",
        ("Plane", "Transform3D"): "transform3DXformInvPlane(other, this)",
        ("Quaternion", "Vector3"): "quaternionXform(this, other)",
        ("AABB", "Transform3D"): "transform3DXformInvAabb(other, this)",
        ("Basis", "Vector3"): "basisXform(this, other)",
        ("Basis", "Basis"): "basisMultiply(this, other)",
        ("Transform3D", "Vector3"): "transform3DXform(this, other)",
        ("Transform3D", "Plane"): "transform3DXformPlane(this, other)",
        ("Transform3D", "AABB"): "transform3DXformAabb(this, other)",
        ("Transform3D", "Transform3D"): "transform3DMultiply(this, other)",
        ("Transform3D", "PackedVector3Array"): "other.map { transform3DXform(this, it) }",
        ("Projection", "Vector4"): "projectionXform(this, other)",
        ("Projection", "Projection"): "projectionMultiply(this, other)",
        ("Quaternion", "Quaternion"): None,  # hand-written (Quaternion.kt, A2)
    }
    if name == "*" and (cls, right) in composite and composite[(cls, right)]:
        ptype = kotlin_type(right)
        rtype = kotlin_type(ret)
        return [(fn, ptype, f"operator fun times(other: {ptype}): {rtype} = {composite[(cls, right)]}")]
    raise SystemExit(f"[generate_builtin_ops] no template for operator {cls} {name} {right}")


def interesting_ops(cls_api: dict) -> list[dict]:
    """The operators a Kotlin member implements (the rest have a language-level reason)."""
    out = []
    for op in cls_api.get("operators", []):
        if op["name"] in ("==", "!=", "not", "in"):
            continue
        out.append(op)
    return out


