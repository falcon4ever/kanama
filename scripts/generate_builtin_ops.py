        if name == "get_center":
            parts = ", ".join(f"position.raw{c} + size.raw{c} * half" for c in comps)
            return f"fun getCenter(): {vec} {{\n  val half = narrowReal(0.5)\n  return {vec}.raw({parts})\n}}"
