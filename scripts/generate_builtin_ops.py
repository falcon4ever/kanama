# How each type's random input is built, identically in Kotlin and GDScript (only constructors and
# parity-proven members, so the inputs themselves are the same bits on both sides).
INPUT_KT = {
    "float": "nv()",
    "int": "ri()",
    "bool": "rb()",
    "Vector2": "Vector2(nv(), nv())",
    "Vector3": "Vector3(nv(), nv(), nv())",
    "Vector4": "Vector4(nv(), nv(), nv(), nv())",
    "Quaternion": "Quaternion(nv(), nv(), nv(), nv()).normalized()",
    "Color": "Color(nv(), nv(), nv(), nv())",
    "Plane": "Plane(Vector3(nv(), nv(), nv()).normalized(), nv())",
    "Rect2": "Rect2(Vector2(nv(), nv()), Vector2(nv(), nv()).abs())",
    "AABB": "AABB(Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()).abs())",
    "Basis": "Basis(Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()))",
    "Transform2D": "Transform2D(Vector2(nv(), nv()), Vector2(nv(), nv()), Vector2(nv(), nv()))",
    "Transform3D": "Transform3D(Basis(Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv())), Vector3(nv(), nv(), nv()))",
    "Projection": "Projection(Vector4(nv(), nv(), nv(), nv()), Vector4(nv(), nv(), nv(), nv()), Vector4(nv(), nv(), nv(), nv()), Vector4(nv(), nv(), nv(), nv()))",
    "Vector2i": "Vector2i(ri(), ri())",
    "Vector3i": "Vector3i(ri(), ri(), ri())",
    "Vector4i": "Vector4i(ri(), ri(), ri(), ri())",
    "Rect2i": "Rect2i(Vector2i(ri(), ri()), Vector2i(ri(), ri()).abs())",
    "RID": "RID(rl())",
    "PackedVector2Array": "listOf(Vector2(nv(), nv()), Vector2(nv(), nv()), Vector2(nv(), nv()))",
    "PackedVector3Array": "listOf(Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()), Vector3(nv(), nv(), nv()))",
}
# Facade inputs: rotations where an engine method asserts one (MATH_CHECKS), small indices.
FACADE_INPUT_KT = dict(INPUT_KT)
FACADE_INPUT_KT.update(
    {
        "int": "rs()",
        # Unit vectors: slide/reflect/bounce/rotated/slerp assert normalized arguments.
        "Vector2": "Vector2(nv(), nv()).normalized()",
        "Vector3": "Vector3(nv(), nv(), nv()).normalized()",
        "Basis": "Basis(Quaternion(nv(), nv(), nv(), nv()).normalized())",
        "Transform3D": "Transform3D(Basis(Quaternion(nv(), nv(), nv(), nv()).normalized()), Vector3(nv(), nv(), nv()))",
        "Transform2D": "rotation2D(Vector2(nv(), nv()).normalized(), Vector2(nv(), nv()))",
        "String": "\"#ff8000\"",
    }
)
# Non-zero integer divisors (Kotlin throws and GDScript errors on integer division by zero).
NONZERO_KT = {
    "int": "rnz()",
    "Vector2i": "Vector2i(rnz(), rnz())",
    "Vector3i": "Vector3i(rnz(), rnz(), rnz())",
    "Vector4i": "Vector4i(rnz(), rnz(), rnz(), rnz())",
}


def to_gd(expr: str) -> str:
    """The GDScript spelling of an INPUT_KT expression."""
    expr = expr.replace("RID(rl())", "rid_from(rl())")
    expr = expr.replace("rotation2D(", "rotation_2d(")
    return expr


def gd_input(godot_type: str, expr: str) -> str:
    if godot_type in LIST_TYPES:
        assert expr.startswith("listOf(") and expr.endswith(")")
        return f"{godot_type}([{to_gd(expr[len('listOf('):-1])}])"
    return to_gd(expr)


def call_args(m: dict, table: dict, nonzero: bool = False) -> list[tuple[str, str, str]]:
    out = []
    for arg in m.get("arguments", []):
        t = arg["type"]
        expr = table[t]
        if t == "int" and table is INPUT_KT:
            expr = "ri()"
        out.append((t, expr + (".toLong()" if t == "int" else ""), gd_input(t, expr)))
    return out


# Per pure parity entry: the class, the Godot types its inputs use, and the Kotlin member it calls
# (name, first parameter type or None) -- what the Web parity test needs to know whether the Web
# value types can run the same entry.
ENTRY_META: dict[str, tuple[str, tuple[str, ...], str, str | None]] = {}


def parity_entries(members: list[Member]) -> tuple[list[tuple[str, list[str], list[str]]], list[tuple[str, list[str], list[str]]]]:
    """(name, kotlin lines, gdscript lines) per parity entry: (pure, facade)."""
    ENTRY_META.clear()
    pure: list = []
    facade: list = []
    done: set[str] = set()
    for member in members:
        if member.impl == "deferred":
            continue
        if member.kind == "op":
            op = member.godot
            key = member.key
            if key in done:
                continue
            done.add(key)
            right = op.get("right_type", "")
            cls = member.cls
            if op["name"] in COMPARE_OPS:
                fn, ptype = "compareTo", cls
            elif not right:
                fn, ptype = OP_KOTLIN[op["name"]], None
            else:
                fn = OP_KOTLIN[op["name"]]
                ptype = {"int": "Long", "float": "Double"}.get(right) or kotlin_type(right)
            ENTRY_META[key] = (cls, (cls, right) if right else (cls,), fn, ptype)
            lt = INPUT_KT[cls]
            kt: list[str] = [f"val l = {lt}"]
            gd: list[str] = [f"var l = {gd_input(cls, lt)}"]
            if not right:
                sym = "-" if op["name"] == "unary-" else "+"
                kt.append(f'mix("{key}", {sym}l)')
                gd.append(f'mix("{key}", {sym}l)')
            else:
                divisor = op["name"] in ("/", "%") and (VALUE_TYPES.get(cls) and VALUE_TYPES[cls].kind == "int") and right in NONZERO_KT
                rt = NONZERO_KT[right] if divisor else INPUT_KT[right]
                if right == "int":
                    kt.append(f"val r = {rt}.toLong()")
                else:
                    kt.append(f"val r = {rt}")
                gd.append(f"var r = {gd_input(right, rt)}")
                sym = op["name"]
                kt.append(f'mix("{key}", l {sym} r)')
                gd.append(f'mix("{key}", l {sym} r)')
            pure.append((key, kt, gd))
            continue
        m = member.godot
        cls = member.cls
        kn = kotlin_name(cls, m["name"])
        is_facade = member.impl in ("facade",) or (member.impl == "hand" and member_calls_engine(member))
        table = FACADE_INPUT_KT if is_facade else INPUT_KT
        args = call_args(m, table)
        kt = []
        gd = []
        for i, (t, k, g) in enumerate(args):
            kt.append(f"val a{i} = {k}")
            gd.append(f"var a{i} = {g}")
        names = ", ".join(f"a{i}" for i in range(len(args)))
        if member.static:
            kt.append(f'mix("{member.key}", {cls}.{kn}({names}))')
            gd.append(f'mix("{member.key}", {cls}.{m["name"]}({names}))')
        else:
            base = table[cls] if cls in table else INPUT_KT[cls]
            kt.insert(0, f"val b = {base}")
            gd.insert(0, f"var b = {gd_input(cls, base)}")
            prop = PROPERTY_MEMBERS.get((cls, m["name"]))
            kt.append(f'mix("{member.key}", b.{prop})' if prop else f'mix("{member.key}", b.{kn}({names}))')
            gd.append(f'mix("{member.key}", b.{m["name"]}({names}))')
        if not is_facade:
            types = tuple(a["type"] for a in m.get("arguments", [])) + (() if member.static else (cls,))
            ENTRY_META[member.key] = (cls, types, kn, None)
        (facade if is_facade else pure).append((member.key, kt, gd))
    return pure, facade


