            "\t\t\tmix_long(name, PackedFloat64Array([value]).to_byte_array().decode_s64(0))",
            "\telif value is bool:",
            "\t\tmix_long(name, 1 if value else 0)",
            "\telif value is int:",
            "\t\tmix_long(name, value)",
            "\telif value is String:",
            "\t\tfor i in value.length():",
            "\t\t\tmix_long(name, value.unicode_at(i))",
            "\telif value is RID:",
            "\t\tmix_long(name, value.get_id())",
            "\telif value is Vector2 or value is Vector2i:",
            "\t\tfor c in [value.x, value.y]: mix(name, c)",
            "\telif value is Vector3 or value is Vector3i:",
            "\t\tfor c in [value.x, value.y, value.z]: mix(name, c)",
            "\telif value is Vector4 or value is Vector4i or value is Quaternion:",
            "\t\tfor c in [value.x, value.y, value.z, value.w]: mix(name, c)",
            "\telif value is Color:",
            "\t\tfor c in [value.r, value.g, value.b, value.a]: mix(name, c)",
