#!/usr/bin/env python3
"""Generate the Kotlin/Wasm Web wrapper tree from the Web call contract (task 96).

Every opcode in `scripts/platform_backend_calls.json` becomes one member on the Godot class that
owns it, in `web-runtime/src/commonMain/kotlin/net/multigesture/kanama/api/generated/<Class>.kt`
(one class, one file). The member's name, parameters, defaults and return type come from
`extension_api.json` (the same source the native wrapper generator reads), the call itself goes
straight to `GodotBackendCalls.invoke<Shape>(InitialGodotCallDescriptors.X, ...)`, so the former
hand-written probe + wrapper pair collapses into one generated layer.

What stays hand-written is explicit and short: `WEB_HANDSHAPED` names the bespoke facades that
live in hand-written files under `api/`, and `CLASS_POLICY[...]["custom"]` carries the Web-specific
members the contract cannot express (compositions over several opcodes, Kotlin-side mirrors,
lifetime helpers). Both are checked by `--check`, which also fails if a hand-written file under
`api/` dispatches an opcode the generated tree owns.

Usage:
    python3 scripts/generate_web_wrappers.py            # regenerate the tree
    python3 scripts/generate_web_wrappers.py --check    # committed == fresh regen, gate mode
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from generate_web_backend import SIGNATURES  # noqa: E402  (SPI parameter list per call shape)
from platform_backend_contract import INITIAL_BACKEND_CALLS, BackendCallPolicy  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
API_PATH = ROOT / "extension_api.json"
API_DIR = ROOT / "web-runtime/src/commonMain/kotlin/net/multigesture/kanama/api"
GENERATED_DIR = API_DIR / "generated"
TAG = "[web_wrappers]"

HEADER = "// Generated by scripts/generate_web_wrappers.py — do not edit.\n"


class GenerationError(RuntimeError):
    pass


# --------------------------------------------------------------------------------------------------
# extension_api.json access
# --------------------------------------------------------------------------------------------------


class Api:
    def __init__(self, path: Path = API_PATH) -> None:
        payload = json.loads(path.read_text())
        self.classes: dict[str, dict] = {c["name"]: c for c in payload["classes"]}
        self.utilities: dict[str, dict] = {u["name"]: u for u in payload["utility_functions"]}
        self.global_enums: dict[str, dict] = {e["name"]: e for e in payload["global_enums"]}
        self.singletons: set[str] = {s["name"] for s in payload.get("singletons", ())}

    def parent(self, name: str) -> str | None:
        return self.classes[name].get("inherits")

    def chain(self, name: str) -> list[str]:
        out = []
        while name:
            out.append(name)
            name = self.parent(name)
        return out

    def method(self, call: BackendCallPolicy) -> dict:
        if call.scope == "utility":
            return self.utilities[call.method_name]
        for method in self.classes[call.class_name].get("methods", ()):
            if method["name"] == call.method_name and method["hash"] == call.expected_hash:
                return method
        raise GenerationError(f"opcode {call.opcode}: {call.class_name}.{call.method_name} not in API")

    def property_for(self, class_name: str, method_name: str) -> dict | None:
        """The non-indexed property of `class_name` (or an ancestor) that `method_name` gets/sets."""
        for owner in self.chain(class_name):
            for prop in self.classes[owner].get("properties", ()):
                if "index" in prop:
                    continue
                if prop.get("setter") == method_name or prop.get("getter") == method_name:
                    return prop
        return None

    def enum_values(self, owner: str, enum: str) -> dict[str, int]:
        source = (
            self.global_enums.get(enum)
            if owner == "@GlobalScope"
            else next((e for e in self.classes[owner].get("enums", ()) if e["name"] == enum), None)
        )
        if source is None:
            raise GenerationError(f"enum {owner}.{enum} not in API")
        return {v["name"]: v["value"] for v in source["values"]}

    def constant(self, owner: str, name: str) -> int:
        for constant in self.classes[owner].get("constants", ()):
            if constant["name"] == name:
                return constant["value"]
        raise GenerationError(f"constant {owner}.{name} not in API")

    def has_signal(self, class_name: str, signal: str) -> bool:
        return any(
            s["name"] == signal
            for owner in self.chain(class_name)
            for s in self.classes[owner].get("signals", ())
        )


# --------------------------------------------------------------------------------------------------
# Naming
# --------------------------------------------------------------------------------------------------

KEYWORD_RENAMES = {"internal": "internalMode", "class": "className", "object": "target", "RID": "rid"}


def camel(snake: str) -> str:
    parts = snake.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def param_name(godot_name: str) -> str:
    return KEYWORD_RENAMES.get(godot_name, camel(godot_name))


def kotlin_class_name(godot_name: str) -> str:
    return "GodotObject" if godot_name == "Object" else godot_name


# --------------------------------------------------------------------------------------------------
# Rendering (filled in family by family)
# --------------------------------------------------------------------------------------------------


@dataclass
class ClassFile:
    name: str
    lines: list[str] = field(default_factory=list)

    def render(self) -> str:
        return HEADER + "\n".join(self.lines) + "\n"


def render_all(api: Api) -> dict[str, str]:
    """Render every generated file: file name -> content."""
    files: dict[str, str] = {}
    return files


# --------------------------------------------------------------------------------------------------
# Entry point
# --------------------------------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=GENERATED_DIR)
    parser.add_argument("--check", action="store_true", help="fail if the committed tree drifts")
    args = parser.parse_args()

    api = Api()
    rendered = render_all(api)
    out_dir: Path = args.output_dir

    if args.check:
        failures: list[str] = []
        committed = {p.name: p for p in out_dir.glob("*.kt")} if out_dir.is_dir() else {}
        for name, text in rendered.items():
            path = committed.pop(name, None)
            if path is None:
                failures.append(f"missing generated file {name}")
            elif path.read_text() != text:
                failures.append(f"drift in {name}")
        for name in sorted(committed):
            failures.append(f"stray file in generated tree: {name}")
        if failures:
            for failure in failures:
                print(f"{TAG} FAIL {failure}", file=sys.stderr)
            print(f"{TAG} run scripts/generate_web_wrappers.py to regenerate", file=sys.stderr)
            return 1
        print(f"{TAG} PASS {len(rendered)} generated files match the contract")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*.kt"):
        if stale.name not in rendered:
            stale.unlink()
    for name, text in rendered.items():
        (out_dir / name).write_text(text)
    print(f"{TAG} wrote {len(rendered)} files to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
